// Generates src/SpiritAI/skills/openui/SKILL.md from the @openuidev/react-ui
// library the Renderer draws with. The skill file is fully generated: the only
// hand-owned words are the frontmatter below (skill-discovery metadata) and
// this file. Agent behavior rules live in config/spirit.yaml, not here.
import { generateSystemPrompt } from "@openuidev/lang-core";
import { openuiLibrary, openuiPromptOptions } from "@openuidev/react-ui";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const out = fileURLToPath(new URL("../../../src/SpiritAI/skills/openui/SKILL.md", import.meta.url));

const frontmatter = `---
name: openui
description: >-
  Use this when a reply needs more than prose: a chart, a table, a form, a
  button or choice, or anything more visual. Every reply is one openui-lang
  program with prose inside TextContent, and this skill is the whole component
  vocabulary.
---
`;

const body = generateSystemPrompt({
  library: openuiLibrary.toSpec(),
  promptOptions: { ...openuiPromptOptions },
});

const content = `${frontmatter}
<!-- Fully generated by \`npm run gen:openui\` from @openuidev/react-ui. Do not edit by hand. -->
${body}`;

if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== content) {
    console.error("skills/openui/SKILL.md is stale: run `npm run gen:openui` in src/web.");
    process.exit(1);
  }
  console.log("skills/openui/SKILL.md is current.");
} else {
  writeFileSync(out, content);
  console.log(`wrote ${out} (${content.length} chars)`);
}
